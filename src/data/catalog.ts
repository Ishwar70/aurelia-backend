function expand(draft: Draft, index: number): Product {
  const now = new Date(Date.UTC(2026, 10, 18 - (index % 12))).toISOString();
  const productId = `prd_${draft.slug.replace(/-/g, "_")}`;
  const variants: Variant[] = [];
  for (const color of draft.colors) {
    for (const size of draft.sizes) {
      const sizeId = size.toLowerCase().replace(/\s+/g, "");
      variants.push({
        id: `var_${draft.slug.replace(/-/g, "_")}_${color.id}_${sizeId}`,
        productId,
        sku: `AUR-${draft.slug}-${color.id}-${sizeId}`.toUpperCase(),
        options: [
          { name: "color", label: color.label },
          { name: "size", label: size },
        ],
        colorFamily: color.family,
        colorHex: color.hex,
        pricing: {
          currency: "INR",
          listMinor: rupeesToMinor(draft.listRupees),
          saleMinor: draft.saleRupees ? rupeesToMinor(draft.saleRupees) : null,
        },
        status: "active",
      });
    }
  }
  return {
    id: productId,
    storeId: STORE_ID,
    schemaVersion: 1,
    status: "active",
    name: draft.name,
    slug: draft.slug,
    brand: "AURELIA",
    department: draft.department,
    category: draft.category,
    categorySlug: draft.categorySlug,
    subcategory: draft.subcategory,
    description: { short: draft.short, details: draft.details },
    attributes: { material: draft.material, fit: draft.fit, occasion: draft.occasion, care: draft.care },
    seo: { title: `${draft.name} | AURELIA`, description: draft.short },
    media: draft.images.map((image) => photo(image.photo, image.alt)),
    tags: draft.tags,
    rating: { average: draft.rating[0], count: draft.rating[1] },
    sizeGuide: draft.sizeGuide,
    collectionIds: draft.collections,
    variants,
    createdBy: "staff_seed",
    updatedBy: "staff_seed",
    createdAt: now,
    updatedAt: now,
    publishedAt: now,
  };
}

export function buildProducts(): Product[] {
  return drafts.map(expand);
}

